// Turns a plan into documents people and coding agents can use.
import type { Plan, PlanRecord } from "./plan";

const bullets = (items: string[]) => items.map((i) => `- ${i}`).join("\n");
const label = { must: "Must have", should: "Should have", later: "Later" } as const;

function section(title: string, body: string): string {
  return body.trim() ? `## ${title}\n\n${body.trim()}\n` : "";
}

export function featuresMarkdown(plan: Plan): string {
  return (["must", "should", "later"] as const)
    .map((p) => {
      const list = plan.features.filter((f) => f.priority === p);
      if (!list.length) return "";
      const items = list
        .map((f) => {
          const criteria = f.acceptanceCriteria.length ? `\n${f.acceptanceCriteria.map((c) => `  - [ ] ${c}`).join("\n")}` : "";
          return `- **${f.name}**: ${f.description}${criteria}`;
        })
        .join("\n");
      return `### ${label[p]}\n\n${items}\n`;
    })
    .filter(Boolean)
    .join("\n");
}

export function planToMarkdown(record: PlanRecord): string {
  const p = record.plan;
  const out = [
    `# ${p.title || "Untitled plan"}`,
    p.oneLiner ? `\n_${p.oneLiner}_\n` : "",
    section(
      "Summary",
      [p.summary.problem && `**Problem.** ${p.summary.problem}`, p.summary.solution && `**Solution.** ${p.summary.solution}`, p.summary.audience && `**For.** ${p.summary.audience}`]
        .filter(Boolean)
        .join("\n\n"),
    ),
    section(
      "Open questions",
      p.openQuestions.map((q, i) => `${i + 1}. **${q.question}** ${q.whyItMatters}`).join("\n"),
    ),
    section("Users", p.users.map((u) => `- **${u.name}**: wants ${u.goal}. Today: ${u.pain}`).join("\n")),
    section("Features", featuresMarkdown(p)),
    section("User flows", p.userFlows.map((f) => `### ${f.name}\n\n${f.steps.map((s, i) => `${i + 1}. ${s}`).join("\n")}\n`).join("\n")),
    section(
      "Architecture",
      [
        p.architecture.overview,
        p.architecture.components.length
          ? `| Component | Responsibility | Technology |\n| --- | --- | --- |\n${p.architecture.components.map((c) => `| ${c.name} | ${c.responsibility} | ${c.tech} |`).join("\n")}`
          : "",
        p.architecture.integrations.length ? `**Integrations**\n\n${bullets(p.architecture.integrations.map((i) => `${i.name}: ${i.purpose}`))}` : "",
      ]
        .filter(Boolean)
        .join("\n\n"),
    ),
    section(
      "Data model",
      p.dataModel.map((d) => `### ${d.entity}\n\n${bullets(d.fields.map((f) => `\`${f}\``))}${d.notes ? `\n\n${d.notes}` : ""}\n`).join("\n"),
    ),
    section("API", p.api.length ? `| Method | Path | Purpose |\n| --- | --- | --- |\n${p.api.map((a) => `| ${a.method} | \`${a.path}\` | ${a.purpose} |`).join("\n")}` : ""),
    section(
      "Build plan",
      p.milestones
        .map((m, i) => `### ${i + 1}. ${m.name}${m.estimate ? ` (${m.estimate})` : ""}\n\n${m.goal}\n\n${bullets(m.deliverables)}\n`)
        .join("\n"),
    ),
    section("Risks", p.risks.map((r) => `- **${r.risk}** (${r.impact} impact). ${r.mitigation}`).join("\n")),
    section(
      "Business",
      [
        p.business.pricing && `**Pricing.** ${p.business.pricing}`,
        p.business.goToMarket && `**Getting customers.** ${p.business.goToMarket}`,
        p.business.successMetrics.length ? `**How to tell it is working**\n\n${bullets(p.business.successMetrics)}` : "",
      ]
        .filter(Boolean)
        .join("\n\n"),
    ),
    section("Assumptions", bullets(p.assumptions)),
    `\n---\nGenerated by Apex with ${record.model} on ${new Date(record.createdAt).toLocaleDateString()}. AI-generated: review before relying on it.\n`,
  ];
  return out.filter(Boolean).join("\n");
}

// A brief for a coding agent (Claude Code, Cursor, Codex): scope, constraints and the
// first milestone, with the full plan attached for reference.
export function planToAgentBrief(record: PlanRecord): string {
  const p = record.plan;
  const first = p.milestones[0];
  const must = p.features.filter((f) => f.priority === "must");
  return [
    `# Build brief: ${p.title || "Untitled"}`,
    "",
    p.oneLiner,
    "",
    "## Your task",
    "",
    first
      ? `Build milestone 1, "${first.name}": ${first.goal}\n\nDeliverables:\n${bullets(first.deliverables)}`
      : "Build the must-have features below.",
    "",
    "## Must-have features and their acceptance criteria",
    "",
    must
      .map((f) => `### ${f.name}\n\n${f.description}\n\n${f.acceptanceCriteria.map((c) => `- [ ] ${c}`).join("\n")}`)
      .join("\n\n") || "_None listed._",
    "",
    "## Stack",
    "",
    bullets(p.architecture.components.map((c) => `${c.name}: ${c.tech} (${c.responsibility})`)),
    "",
    "## Working rules",
    "",
    "- Build only what milestone 1 needs; do not start later features.",
    "- Write tests for every acceptance criterion above.",
    "- Do not decide the open questions below yourself. Stop and ask, or leave a clearly marked TODO.",
    "",
    "## Open questions (owner decides)",
    "",
    p.openQuestions.map((q) => `- ${q.question}`).join("\n") || "_None._",
    "",
    "## Assumptions already made",
    "",
    bullets(p.assumptions) || "_None._",
    "",
    "---",
    "",
    "Full plan for reference:",
    "",
    planToMarkdown(record),
  ].join("\n");
}

export function fileSlug(plan: Plan): string {
  return (plan.title || "plan").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60) || "plan";
}
